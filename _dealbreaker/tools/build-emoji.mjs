// Builds x/7a3797625d3c2330/js/emoji-data.js from emoji-datasource's emoji.json:
// the :short_names: people type in chat (Slack/Discord style), and the list of
// Apple emoji images, so every device can show emoji the iPhone way.
//
//   npm pack emoji-datasource@16.0.0 && tar xzf emoji-datasource-16.0.0.tgz
//   node _dealbreaker/tools/build-emoji.mjs package/emoji.json

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const src = process.argv[2];
if (!src) throw new Error("usage: node build-emoji.mjs path/to/emoji.json");
const data = JSON.parse(readFileSync(src, "utf8"));
const out = fileURLToPath(new URL("../../x/7a3797625d3c2330/js/emoji-data.js", import.meta.url));

const char = (unified) => String.fromCodePoint(...unified.split("-").map((h) => parseInt(h, 16)));

const names = {};
const images = new Set();
const skins = new Set();
// Most-used first, so suggestions list the likely pick first.
for (const e of [...data].sort((a, b) => a.sort_order - b.sort_order)) {
  if (!e.has_img_apple) continue;
  images.add(e.image.replace(/\.png$/, ""));
  for (const n of e.short_names) if (!(n in names)) names[n] = char(e.unified);
  if (e.skin_variations) {
    skins.add(char(e.unified));
    for (const v of Object.values(e.skin_variations)) if (v.has_img_apple) images.add(v.image.replace(/\.png$/, ""));
  }
}

const js = `// Generated by _dealbreaker/tools/build-emoji.mjs from emoji-datasource 16.0.0. Don't edit by hand.

/** :name: → emoji, most common first. */
export const NAMES = ${JSON.stringify(names)};

/** Apple emoji images on the CDN (file names without .png). */
export const APPLE = new Set(${JSON.stringify([...images].join(" "))}.split(" "));

/** Emoji that take a skin tone. */
export const SKINS = new Set(${JSON.stringify([...skins])});
`;
writeFileSync(out, js);
console.log(`${Object.keys(names).length} names, ${images.size} images, ${skins.size} skin-tone emoji → ${out} (${Math.round(js.length / 1024)} KB)`);

// The chat's emoji menu (Phase 6+): every emoji by category, Discord style,
// with all its names for searching. A separate file, loaded the first time
// the menu opens.
const GROUPS = [
  ["people", "People", "😀", ["Smileys & Emotion", "People & Body"]],
  ["nature", "Nature", "🌿", ["Animals & Nature"]],
  ["food", "Food & Drink", "🍔", ["Food & Drink"]],
  ["activities", "Activities", "🎮", ["Activities"]],
  ["travel", "Travel & Places", "🚲", ["Travel & Places"]],
  ["objects", "Objects", "💡", ["Objects"]],
  ["symbols", "Symbols", "❤️", ["Symbols"]],
  ["flags", "Flags", "🏁", ["Flags"]],
];
const groups = GROUPS.map(([id, name, icon, cats]) => ({
  id, name, icon,
  // "emoji names…" entries, one per emoji, in the usual order.
  items: [...data].filter((e) => e.has_img_apple && cats.includes(e.category)).sort((a, b) => a.sort_order - b.sort_order)
    .map((e) => [char(e.unified), e.short_names.join(" "), e.skin_variations ? 1 : 0]),
}));
const groupsOut = fileURLToPath(new URL("../../x/7a3797625d3c2330/js/emoji-groups.js", import.meta.url));
const gjs = `// Generated by _dealbreaker/tools/build-emoji.mjs from emoji-datasource 16.0.0. Don't edit by hand.

/** The emoji menu: [{ id, name, icon, items: [[emoji, "names…", takesSkinTone]] }]. */
export const GROUPS = ${JSON.stringify(groups)};
`;
writeFileSync(groupsOut, gjs);
console.log(`${groups.reduce((n, g) => n + g.items.length, 0)} emoji in ${groups.length} groups → ${groupsOut} (${Math.round(gjs.length / 1024)} KB)`);
